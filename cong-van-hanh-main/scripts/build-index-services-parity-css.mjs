import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const legacyRoot = path.resolve(projectRoot, "..", "Hành chính");
const outputPath = path.join(
  projectRoot,
  "public",
  "legacy",
  "index-services-parity.css",
);

function extractStyle(html, sourceName) {
  const match = html.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
  if (!match) {
    throw new Error(`Không tìm thấy <style> trong ${sourceName}.`);
  }
  return match[1].trim();
}

const sources = [
  "AppStyles.html",
  "UiSharedPrimitives.html",
  "UiSharedControls.html",
];

const parts = [];
for (const sourceName of sources) {
  const sourcePath = path.join(legacyRoot, sourceName);
  const html = await readFile(sourcePath, "utf8");
  parts.push(
    `/* Nguồn 1:1: ${sourceName}. Không sửa tay file sinh ra này. */\n${extractStyle(
      html,
      sourceName,
    )}`,
  );
}

await writeFile(
  outputPath,
  `/* Generated by scripts/build-index-services-parity-css.mjs */\n${parts.join(
    "\n\n",
  )}\n`,
  "utf8",
);

console.log(`Đã tạo ${outputPath}.`);
